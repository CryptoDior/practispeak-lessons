/** Audio slug with US spellings swapped back to UK ("favorite-song" -> "favourite-song"), or null if nothing changes. */
export function ukSlugVariant(slug: string): string | null {
  let changed = false;
  const out = slug
    .split('-')
    .map((t) => {
      const uk = US_TO_UK[t];
      if (uk) {
        changed = true;
        return uk;
      }
      return t;
    })
    .join('-');
  return changed ? out : null;
}
